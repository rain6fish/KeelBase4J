-- The second sample business module: the projects the PM reference tools read, and the task rows
-- they write. It rides in the core for the same reason the CRM tables do — the core ships the tools
-- and the endpoints, and schema validation checks every mapped entity.
--
-- These are not governance state. Like `customers` / `follow_ups`, they are the kind of thing a host
-- already has, and the embedding rule is that whatever the host has, the host keeps (ADR-0017 §1.1).
--
-- Dialect: H2, as in V1/V2. Immutable once applied; changes are new versions.
--
-- 第二个示例业务模块：PM 参考工具读的项目，以及它们写的任务行。它随核心一起走，理由与 CRM 那两张表相同
-- —— 工具与端点由核心提供，而 schema 校验会检查**每一个**被映射的实体。
--
-- 这些**不是**治理状态。与 `customers` / `follow_ups` 一样，它们是宿主多半已经有的那类东西，而嵌入规则是
-- 「宿主已经做了的，归宿主」（ADR-0017 §1.1）。
--
-- 方言：H2，与 V1/V2 相同。一旦应用即不可改；变更走新版本。

CREATE TABLE pm_projects (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    -- active | on_hold | done.
    status        VARCHAR(255) NOT NULL,
    -- low | medium | high.
    risk_level    VARCHAR(255) NOT NULL,
    description   VARCHAR(1000),
    owner_user_id VARCHAR(255) NOT NULL,
    -- The row range facts, the same shape `customers` carries.
    org_id        BIGINT,
    dept_id       BIGINT,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE pm_tasks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT       NOT NULL,
    title         VARCHAR(255) NOT NULL,
    -- open | done.
    status        VARCHAR(255) NOT NULL,
    -- The deadline-risk analysis compares this date, so it is a date rather than free text.
    due_date      DATE,
    owner_user_id VARCHAR(255) NOT NULL,
    org_id        BIGINT,
    dept_id       BIGINT,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- Soft delete: revoking this write is a local compensation, so the row stays and is marked.
    deleted_at    TIMESTAMP(6) WITH TIME ZONE
);
