-- The governance policy: one row holding it, and one row per version it has been.
--
-- The policy is stored as the JSON the frozen `governance-policy` object describes, rather than
-- shredded into columns: the object's `tools` map is keyed by tool name and its overrides are open
-- (`additionalProperties`), so a table per field would be this runtime inventing a shape the contract
-- deliberately left open.
--
-- The history table exists because a policy change is a governance act and nothing else records it:
-- the operations audit deliberately excludes the AI surface, and an AI-surface endpoint is not a
-- business operation. Each accepted write leaves the revision it produced — a fingerprint of the
-- normalized content, so re-submitting the same policy produces the same revision rather than a new
-- version of nothing.
--
-- 治理策略：一行存着它，另一行记它曾经是什么。
--
-- 策略按冻结 `governance-policy` 对象所描述的那份 JSON 存，而不是拆成列：该对象的 `tools` 以**工具名**为键、
-- 覆盖项又是**开放的**（`additionalProperties`），所以「一字段一列」等于本运行时**自己发明一个契约刻意留开的形状**。
--
-- 历史表存在，是因为**改策略是一次治理动作、而没有别的东西记它**：操作审计**刻意排除 AI 面**，而 AI 面上的端点
-- 不是业务操作。每一次被接受的写都留下它产出的 revision —— **规范化内容的指纹**，于是重复提交同一份策略得到**同一个**
-- revision，而不是凭空多出一个版本。

CREATE TABLE governance_policy (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_json TEXT NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE governance_policy_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision   VARCHAR(64) NOT NULL,
    policy_json TEXT NOT NULL,
    applied_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
