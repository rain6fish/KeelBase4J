package cn.com.keelbase.coretest;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;

/**
 * {@code V8__audit_row_outcome_backfill.sql} fills `outcome` and `tool` on the rows written before
 * those columns existed, and the whole value of that file is whether its rules match what the writers
 * wrote. So this runs the file itself — read off the classpath, not copied here — against a table
 * holding one row of every shape `GovernedExecutionEngine` and `SideEffectService` produce.
 *
 * <p>Two properties are asserted beyond the mapping. A row that already carries an outcome is left
 * alone, because re-deriving it from the sentence could only be coarser than what the writer knew. And
 * a row whose shape is not a tool outcome stays NULL rather than being guessed into one — a `chat`
 * row has no outcome, and inventing one would put a number in a report that nothing measured.
 *
 * <p>The pre-state table below is written out rather than taken from `V1` because what is under test is
 * the UPDATE's contract with four columns, and a test that built the whole audit schema would be
 * testing Flyway's ordering instead. It is the same trade the TypeScript side made, and it is what
 * caught a column named after the entity's property there instead of the database's.
 *
 * <p>⚠ 分类规则本身**刻意比旧的自由文本读法更细**：旧读法「句子里出现过 `refused` 就匹配」把
 * `blocked` 与 `refused` 折成了一个，而两者是两道不同的闸。本文件按各自的词分开填 —— 于是历史数据里
 * `blocked` 的数会变小、`refused` 会出现，而那正是按列读的意义。
 *
 * <p>`V8` 填的是那些列存在之前写下的行，而这份文件的价值全在于它的规则是否跟写入方写下的一致。故这里
 * **跑的就是那个文件本身**（从 classpath 读，不在这里抄一份），对着 `GovernedExecutionEngine` 与
 * `SideEffectService` 产出的每一种形状各一行。
 *
 * <p>除映射外还有两条性质。**已经带结局的行不动** —— 从句子重新推只会比写入方当时知道的更粗。**不是工具
 * 结局的行留 NULL**，而不是被猜成一个 —— `chat` 行没有结局，编一个出来就是把一个没人量过的数放进报表。
 *
 * <p>下面这张前置表是写出来的，不是取自 `V1`：被测的是那条 UPDATE 与四列的约定，而一个把整套审计 schema
 * 建起来的测试，测的是 Flyway 的顺序。TypeScript 侧做过同一个取舍，也正是它在那里逮到过一个按实体属性名
 * 写、而不是按库列名写的列。
 */
class AuditOutcomeBackfillTest {

    private static final String V8 = "db/keelbase-migration/h2/V8__audit_row_outcome_backfill.sql";

    /** Four columns and an id — everything the UPDATE reads or writes. */
    private static final String PRE_STATE = """
            CREATE TABLE ai_audit_logs (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              action VARCHAR(64) NOT NULL,
              detail VARCHAR(2000) NOT NULL,
              is_error BOOLEAN NOT NULL DEFAULT FALSE,
              outcome VARCHAR(32),
              tool VARCHAR(64))
            """;

    @Test
    void everyShapeTheWritersProduceGetsItsOwnWord() throws Exception {
        try (Connection db = open()) {
            insert(db, "tool_call", "query_customers -> ok", false);
            insert(db, "tool_call", "create_task -> ok (effect 7 reused: the same call)", false);
            insert(db, "tool_call", "send_email -> fail: SMTP refused the connection", true);
            insert(db, "tool_call", "delete_customer refused: 403 FORBIDDEN", true);
            insert(db, "tool_call", "expense_claim blocked (risk policy)", true);
            insert(db, "tool_call", "issue_refund pending confirmation", false);
            insert(db, "tool_call", "wire_transfer awaiting a second person", false);
            insert(db, "tool_call", "archive_customer attempted", false);
            insert(db, "tool_confirmation", "create_event approved (inline)", false);
            insert(db, "tool_confirmation", "create_event declined (offline)", false);
            insert(db, "tool_confirmation", "create_event execution retried", false);
            insert(db, "effect_revoke", "create_task revoked (effect 3, local -> deleted)", false);

            run(db);

            Map<String, String> got = new LinkedHashMap<>();
            for (String[] row : read(db)) {
                got.put(row[0] + "|" + row[1], row[2] + " / " + row[3]);
            }
            assertEquals(Map.ofEntries(
                    Map.entry("tool_call|query_customers -> ok", "executed / query_customers"),
                    Map.entry("tool_call|create_task -> ok (effect 7 reused: the same call)",
                            "executed / create_task"),
                    Map.entry("tool_call|send_email -> fail: SMTP refused the connection",
                            "failed / send_email"),
                    Map.entry("tool_call|delete_customer refused: 403 FORBIDDEN",
                            "refused / delete_customer"),
                    Map.entry("tool_call|expense_claim blocked (risk policy)",
                            "blocked / expense_claim"),
                    Map.entry("tool_call|issue_refund pending confirmation", "pending / issue_refund"),
                    Map.entry("tool_call|wire_transfer awaiting a second person",
                            "pending / wire_transfer"),
                    Map.entry("tool_call|archive_customer attempted", "attempted / archive_customer"),
                    Map.entry("tool_confirmation|create_event approved (inline)",
                            "approved / create_event"),
                    Map.entry("tool_confirmation|create_event declined (offline)",
                            "declined / create_event"),
                    Map.entry("tool_confirmation|create_event execution retried",
                            "attempted / create_event"),
                    Map.entry("effect_revoke|create_task revoked (effect 3, local -> deleted)",
                            "revoked / create_task")),
                    got);
        }
    }

    @Test
    void aRowThatAlreadyHasAnOutcomeIsNotReDerivedFromItsSentence() throws Exception {
        try (Connection db = open()) {
            // The sentence says `-> ok`. What the writer knew and wrote is `executed` — and a row that
            // already answers must keep answering, whatever its prose says.
            try (Statement st = db.createStatement()) {
                st.executeUpdate("INSERT INTO ai_audit_logs (action, detail, is_error, outcome, tool)"
                        + " VALUES ('tool_call', 'query_customers -> ok', FALSE, 'failed', 'mine')");
            }
            insert(db, "tool_call", "query_customers -> ok", false);

            run(db);

            List<String[]> rows = read(db);
            assertEquals("failed / mine", rows.get(0)[2] + " / " + rows.get(0)[3]);
            assertEquals("executed / query_customers", rows.get(1)[2] + " / " + rows.get(1)[3]);
        }
    }

    @Test
    void aRowThatIsNotAToolOutcomeStaysNull() throws Exception {
        try (Connection db = open()) {
            insert(db, "chat", "帮我看看上周的客户跟进情况", false);
            insert(db, "knowledge", "retrieved 3 chunks", false);

            run(db);

            for (String[] row : read(db)) {
                assertNull(row[2], row[0] + " has no outcome to state");
                assertNull(row[3], row[0] + " is not about one tool");
            }
        }
    }

    private static Connection open() throws SQLException {
        Connection db = DriverManager.getConnection("jdbc:h2:mem:keelbase-v8;DB_CLOSE_DELAY=-1", "sa", "");
        try (Statement st = db.createStatement()) {
            st.execute("DROP TABLE IF EXISTS ai_audit_logs");
            st.execute(PRE_STATE);
        }
        return db;
    }

    private static void insert(Connection db, String action, String detail, boolean error)
            throws SQLException {
        try (Statement st = db.createStatement()) {
            st.executeUpdate("INSERT INTO ai_audit_logs (action, detail, is_error) VALUES ('" + action
                    + "', '" + detail.replace("'", "''") + "', " + error + ")");
        }
    }

    /** Runs the migration file itself, comments and all, so a change to the file is what is tested. */
    private static void run(Connection db) throws SQLException, IOException {
        String sql;
        try (InputStream in = AuditOutcomeBackfillTest.class.getClassLoader().getResourceAsStream(V8)) {
            if (in == null) {
                throw new IllegalStateException(V8 + " is not on the classpath");
            }
            sql = new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
        try (Statement st = db.createStatement()) {
            st.execute(sql);
        }
    }

    private static List<String[]> read(Connection db) throws SQLException {
        List<String[]> rows = new ArrayList<>();
        try (Statement st = db.createStatement();
                ResultSet rs = st.executeQuery(
                        "SELECT action, detail, outcome, tool FROM ai_audit_logs ORDER BY id")) {
            while (rs.next()) {
                rows.add(new String[] {rs.getString(1), rs.getString(2), rs.getString(3),
                        rs.getString(4)});
            }
        }
        return rows;
    }
}
